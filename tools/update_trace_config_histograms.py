"""Generates Perfetto trace configs from .template.pbtxt files.

Parses each *.template.pbtxt file in cuj/crossbench/trace-config/ as a
TraceConfig protobuf, expands wildcard histogram patterns in the
org.chromium.histogram_sample data source using Chromium's
tools/metrics/histograms/print_expanded_histograms.py, and writes the resulting
TraceConfig textproto to the corresponding .pbtxt file.
"""

from __future__ import annotations

import argparse
import fnmatch
import logging
import re
import subprocess
import sys
from pathlib import Path

from google.protobuf import text_format

WEB_TESTS_ROOT = Path(__file__).resolve().parent.parent
THIRD_PARTY_CROSSBENCH = WEB_TESTS_ROOT / "third_party" / "crossbench"
if str(THIRD_PARTY_CROSSBENCH) not in sys.path:
  sys.path.append(str(THIRD_PARTY_CROSSBENCH))

# pylint: disable=wrong-import-position
from third_party.protoc import trace_config_pb2

# pylint: enable=wrong-import-position

TRACE_CONFIG_DIR = WEB_TESTS_ROOT / "cuj" / "crossbench" / "trace-config"
HISTOGRAM_DATA_SOURCE_NAME = "org.chromium.histogram_sample"
TEMPLATE_SUFFIX = ".template.pbtxt"


def resolve_print_expanded_histograms_script(chromium_src: Path) -> Path:
  rel_script = Path("tools/metrics/histograms/print_expanded_histograms.py")
  for candidate_root in (chromium_src, chromium_src / "src"):
    candidate = candidate_root / rel_script
    if candidate.is_file():
      return candidate
  raise FileNotFoundError(f"Could not find {rel_script} under {chromium_src}. "
                          "Please pass a valid --chromium-src path.")


def fetch_chromium_histograms(script_path: Path, pattern: str) -> list[str]:
  result = subprocess.run(
      [
          sys.executable,
          str(script_path), "--print-names-only", f"--pattern={pattern}"
      ],
      check=True,
      capture_output=True,
      text=True,
  )
  return [line.strip() for line in result.stdout.splitlines() if line.strip()]


def is_wildcard(pattern: str) -> bool:
  return "*" in pattern or "?" in pattern


def expand_patterns(patterns: list[str],
                    all_chromium_histograms: list[str]) -> list[str]:
  expanded: list[str] = []
  seen: set[str] = set()

  for pattern in patterns:
    if is_wildcard(pattern):
      regex = re.compile(fnmatch.translate(pattern))
      matches = [name for name in all_chromium_histograms if regex.match(name)]
      if not matches:
        raise ValueError(
            f"Wildcard pattern {pattern!r} did not match any Chromium "
            "histograms.")
      for match in matches:
        if match not in seen:
          seen.add(match)
          expanded.append(match)
    elif pattern not in seen:
      seen.add(pattern)
      expanded.append(pattern)

  return expanded


def parse_template_config(template_path: Path) -> trace_config_pb2.TraceConfig:
  trace_config = trace_config_pb2.TraceConfig()
  text_format.Parse(template_path.read_text(encoding="utf-8"), trace_config)
  return trace_config


def extract_histogram_patterns(
    trace_config: trace_config_pb2.TraceConfig) -> list[str]:
  patterns: list[str] = []
  for data_source in trace_config.data_sources:
    if data_source.config.name != HISTOGRAM_DATA_SOURCE_NAME:
      continue
    for sample in data_source.config.chromium_histogram_samples.histograms:
      if sample.histogram_name:
        patterns.append(sample.histogram_name)
  return patterns


def generate_trace_config(template_path: Path, output_path: Path,
                          trace_config: trace_config_pb2.TraceConfig,
                          all_chromium_histograms: list[str]) -> None:
  total_histograms = 0
  for data_source in trace_config.data_sources:
    if data_source.config.name != HISTOGRAM_DATA_SOURCE_NAME:
      continue
    samples_config = data_source.config.chromium_histogram_samples
    patterns = [
        s.histogram_name for s in samples_config.histograms if s.histogram_name
    ]
    expanded = expand_patterns(patterns, all_chromium_histograms)
    samples_config.ClearField("histograms")
    for name in expanded:
      samples_config.histograms.add(histogram_name=name)
    total_histograms += len(expanded)

  header = "\n".join([
      "# DO NOT EDIT THIS FILE MANUALLY.",
      f"# This file is generated from {template_path.name}.",
      "# To update, edit the template file and run:",
      "#   vpython3 tools/update_trace_config_histograms.py "
      "--chromium-src <path>",
      "",
  ])
  output_content = header + text_format.MessageToString(trace_config)
  output_path.write_text(output_content, encoding="utf-8")
  logging.info("Generated %s from %s (%d histograms)", output_path,
               template_path.name, total_histograms)


def main(argv: list[str] | None = None) -> int:
  parser = argparse.ArgumentParser(
      description=(
          "Generate Perfetto trace configs from .template.pbtxt files by "
          "expanding wildcard histogram patterns via Chromium's "
          "print_expanded_histograms.py."))
  parser.add_argument(
      "--chromium-src",
      type=Path,
      required=True,
      help="Path to local Chromium src checkout.",
  )
  args = parser.parse_args(argv)

  logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")

  script_path = resolve_print_expanded_histograms_script(
      args.chromium_src.expanduser().resolve())

  template_paths = sorted(TRACE_CONFIG_DIR.glob(f"*{TEMPLATE_SUFFIX}"))
  if not template_paths:
    raise FileNotFoundError(
        f"No *{TEMPLATE_SUFFIX} files found in {TRACE_CONFIG_DIR}")

  parsed_templates: list[tuple[Path, Path, trace_config_pb2.TraceConfig]] = []
  wildcard_regexes: set[str] = set()

  for template_path in template_paths:
    output_name = template_path.name[:-len(TEMPLATE_SUFFIX)] + ".pbtxt"
    output_path = template_path.with_name(output_name)
    trace_config = parse_template_config(template_path)
    for pattern in extract_histogram_patterns(trace_config):
      if is_wildcard(pattern):
        wildcard_regexes.add(fnmatch.translate(pattern))
    parsed_templates.append((template_path, output_path, trace_config))

  combined_pattern = ("|".join(f"(?:{r})" for r in sorted(wildcard_regexes))
                      if wildcard_regexes else ".*")

  logging.info("Running %s ...", script_path)
  chromium_histograms = fetch_chromium_histograms(script_path, combined_pattern)

  for template_path, output_path, trace_config in parsed_templates:
    generate_trace_config(template_path, output_path, trace_config,
                          chromium_histograms)

  return 0


if __name__ == "__main__":
  sys.exit(main())
